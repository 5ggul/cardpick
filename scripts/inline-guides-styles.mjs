// Run after the pinned Tailwind command in guides-tailwind.config.cjs.
// The generated module is bundled into the Pages Function: no runtime file I/O.
import { readFileSync, writeFileSync } from 'node:fs';
const compiled = readFileSync(new URL('../styles/guides-base.css', import.meta.url), 'utf8').trim();
if (!compiled.includes('tailwindcss v3.4.17') || /<\/style/i.test(compiled)) {
  throw new Error('Expected the reviewed Tailwind 3.4.17 stylesheet');
}
// The compiled input is shared. Only the guide hub's generated module opts out
// of late font swaps; family, outlines, weights, sources and ranges stay exact.
const faces = [...compiled.matchAll(/@font-face\{[^}]*\}/g)];
if (faces.length !== 15 || (compiled.match(/font-display:swap/g) || []).length !== 15) {
  throw new Error('Expected the 15 existing local IBM Plex Mono faces');
}
const css = compiled.replace(/@font-face\{[^}]*\}/g, face => {
  if (!face.includes('font-family:IBM Plex Mono;') || !/font-weight:(400|500|600);/.test(face)
      || (face.match(/font-display:swap/g) || []).length !== 1
      || !/src:url\(\/fonts\/ibm-plex-mono\/[-\w]+\.woff2\) format\("woff2"\)/.test(face)) {
    throw new Error('Unexpected guide font declaration; review before regenerating');
  }
  return face.replace('font-display:swap', 'font-display:optional');
});
writeFileSync(new URL('../functions/_lib/guides-style.js', import.meta.url),
  '// Generated by scripts/inline-guides-styles.mjs; do not edit by hand.\n'
  + `export default ${JSON.stringify(css)};\n`);
